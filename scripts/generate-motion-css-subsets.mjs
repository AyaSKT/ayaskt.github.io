// 从 animate.css / animxyz 全量文件中机械抽取实际用到的规则，生成本地子集。
// 规则原样逐字节复制，保证动画视觉效果与全量库完全一致。
// 用法：node scripts/generate-motion-css-subsets.mjs
// 若主题新增用到的 animate.css 动画名或 animxyz token，更新下方允许清单后重新运行。

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const vendorRoot = path.join(root, 'docs/.vitepress/theme/vendor')

/** 主题中实际用到的 animate.css 动画名（class 与同名 keyframes 一并保留）。
 *  来源：
 *  - JS 添加的 animate__* class：sidebar-motion.ts / solution-collapse.ts /
 *    outline-jump-motion.ts / MyLayout.vue / MindMap.vue
 *  - CSS 中直接引用的 keyframes 名：transitions.css / index.css /
 *    sidebar-window.css / library-motion.css / blur.css
 */
const ANIMATE_NAMES = new Set([
  'fadeIn',
  'fadeOut',
  'fadeInLeft',
  'fadeOutLeft',
  'fadeInUp',
  'fadeInDown',
  'fadeOutUp',
  'zoomIn',
  'zoomOut',
])

/** 主题中实际用到的 animxyz utility token（含 in-/out-/appear- 变体自动匹配）。
 *  来源：LibraryMotion.vue 的 xyz 属性字符串。
 */
const XYZ_TOKENS = new Set([
  'fade',
  'small-2',
  'up-1',
  'left-1',
  'duration-6',
  'ease-out',
  'stagger',
  'stagger-0',
  'stagger-1',
  'stagger-rev',
  'stagger-rev-0.35',
  'stagger-rev-0.5',
])

/** 按大括号配平切分顶层规则（min.css 为单行，无嵌套歧义）。 */
function splitTopLevelRules(css) {
  const rules = []
  let depth = 0
  let start = 0
  for (let i = 0; i < css.length; i++) {
    const char = css[i]
    if (char === '{') depth++
    else if (char === '}') {
      depth--
      if (depth === 0) {
        rules.push(css.slice(start, i + 1))
        start = i + 1
      }
    }
  }
  const tail = css.slice(start).trim()
  if (tail) rules.push(tail)
  return rules
}

function buildAnimateSubset() {
  const source = fs.readFileSync(
    path.join(root, 'node_modules/animate.css/animate.min.css'),
    'utf8',
  )
  const body = source.replace(/^@charset "UTF-8";/, '')
  const rules = splitTopLevelRules(body)

  const kept = rules.filter((rule) => {
    if (rule.startsWith('/*')) return false

    const keyframesMatch = rule.match(/^@(?:-webkit-)?keyframes ([\w-]+)/)
    if (keyframesMatch) return ANIMATE_NAMES.has(keyframesMatch[1])

    const selector = rule.slice(0, rule.indexOf('{'))
    const animateClasses = [...selector.matchAll(/\.animate__([\w-]+)/g)].map((m) => m[1])
    if (animateClasses.length === 0) return true // :root、media query 等基础设施

    // 基础设施 class（animated / delay / speed / reduced-motion）全部保留，动画名 class 按清单过滤
    const utilityClasses = new Set([
      'animated', 'infinite', 'repeat-1', 'repeat-2', 'repeat-3',
      'delay-1s', 'delay-2s', 'delay-3s', 'delay-4s', 'delay-5s',
      'faster', 'fast', 'slow', 'slower',
    ])
    return animateClasses.every((name) => utilityClasses.has(name) || ANIMATE_NAMES.has(name))
  })

  const header = '/*! animate.css v4.1.1 subset - https://animate.style/ - MIT License. Generated by scripts/generate-motion-css-subsets.mjs */\n'
  const output = `@charset "UTF-8";${header}${kept.join('')}\n`
  const outPath = path.join(vendorRoot, 'animate/animate-subset.min.css')
  fs.mkdirSync(path.dirname(outPath), { recursive: true })
  fs.writeFileSync(outPath, output)
  return { outPath, size: output.length, kept: kept.length, total: rules.length }
}

function xyzTokenAllowed(token) {
  const bare = token.replace(/^"|"$/g, '').replace(/^(in|out|appear)-/, '')
  return XYZ_TOKENS.has(bare)
}

function buildXyzSubset() {
  const source = fs.readFileSync(
    path.join(vendorRoot, 'animxyz/animxyz.min.css'),
    'utf8',
  )
  const rules = splitTopLevelRules(source)

  const kept = rules.filter((rule) => {
    const selector = rule.slice(0, rule.indexOf('{'))
    const xyzAttrs = [...selector.matchAll(/\[xyz~=([^\]]+)\]/g)].map((m) => m[1])
    // 核心机制（keyframes、.xyz-in/out、nth-child stagger、:root 变量）无属性选择器，全部保留
    if (xyzAttrs.length === 0) return true
    return xyzAttrs.some(xyzTokenAllowed)
  })

  const header = '/*! AnimXYZ subset - https://animxyz.com/ - MIT License. Generated by scripts/generate-motion-css-subsets.mjs */\n'
  const output = `${header}${kept.join('')}\n`
  const outPath = path.join(vendorRoot, 'animxyz/animxyz-subset.min.css')
  fs.writeFileSync(outPath, output)
  return { outPath, size: output.length, kept: kept.length, total: rules.length }
}

const animate = buildAnimateSubset()
const xyz = buildXyzSubset()

for (const result of [animate, xyz]) {
  console.log(
    `${path.relative(root, result.outPath)}: ${result.kept}/${result.total} rules, ${(result.size / 1024).toFixed(1)} KB`,
  )
}
